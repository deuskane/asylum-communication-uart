package tb_UART_bfm_pkg is

  constant C_TB_SCOPE      : string  := "TB_UART_BFM";

  -- Configuration of the DUT
  constant C_CLOCK_FREQ    : integer := 50_000_000;
  constant C_BAUD_RATE     : integer := 115_200;
  constant C_DEPTH_TX      : natural := 16;
  constant C_DEPTH_RX      : natural := 16;
  constant C_CLK_PERIOD    : time    := 1 sec / C_CLOCK_FREQ;
  -- Bit period generated by the DUT : (CLOCK_FREQ/BAUD_RATE) clock cycles
  constant C_BIT_PERIOD    : time    := (C_CLOCK_FREQ / C_BAUD_RATE) * C_CLK_PERIOD;
  -- Reset value of baud_tick_cnt_max_{msb,lsb} : (CLOCK_FREQ/BAUD_RATE)-1
  constant C_BAUD_TICK_CNT_MAX : std_logic_vector(16-1 downto 0) := std_logic_vector(to_unsigned(C_CLOCK_FREQ / C_BAUD_RATE - 1, 16));

  subtype  byte_t is std_logic_vector(8-1 downto 0);
  type     byte_array_t is array (natural range <>) of byte_t;

  -- ctrl_tx / ctrl_rx : [0] enable, [1] parity enable, [2] parity odd,
  -- [3] loopback (tx_use_loopback / rx_use_loopback), [4] flow control
  -- (cts_enable / rts_enable)
  constant CTRL_EN         : byte_t := x"01";
  constant CTRL_EN_EVEN    : byte_t := x"03";
  constant CTRL_EN_ODD     : byte_t := x"07";
  constant CTRL_LOOPBACK   : byte_t := x"08";
  constant CTRL_FLOW_CTRL  : byte_t := x"10";

  -- Patterns : data bit 0 at 1 and at 0, all parities
  constant PATTERNS        : byte_array_t := (x"A5", x"5A", x"01", x"80", x"FF", x"00", x"3C", x"C3");

  -- Parity of a frame
  type     parity_t is (PARITY_NONE, PARITY_EVEN, PARITY_ODD);

  -- SBI accesses : up to 10 wait states (isr read wait state, blocking
  -- write of data)
  constant C_SBI_CFG       : t_sbi_bfm_config := C_SBI_BFM_CONFIG_DEFAULT;

  -- Expected parity bit of data
  function parity_bit
    (constant data     : in    byte_t
    ;constant parity   : in    parity_t
    ) return std_logic;

  function to_string
    (constant parity   : in    parity_t
    ) return string;

  -- Byte of value i
  function byte
    (constant i        : in    natural
    ) return byte_t;

  -- SBI write
  procedure wr
    (constant addr     : in    unsigned
    ;constant data     : in    byte_t
    ;constant msg      : in    string
    ;signal   clk      : in    std_logic
    ;signal   sbi_if   : inout t_sbi_if
    );

  -- SBI read
  procedure rd
    (constant addr     : in    unsigned
    ;variable data     : out   byte_t
    ;constant msg      : in    string
    ;signal   clk      : in    std_logic
    ;signal   sbi_if   : inout t_sbi_if
    );

  -- SBI read and check
  procedure chk
    (constant addr     : in    unsigned
    ;constant data     : in    byte_t
    ;constant msg      : in    string
    ;signal   clk      : in    std_logic
    ;signal   sbi_if   : inout t_sbi_if
    );

  -- SBI blocking read of data and check : waits up to 16 bit periods for
  -- a received byte (a frame lasts 10 or 11 bit periods)
  procedure chk_blocking
    (constant data     : in    byte_t
    ;constant msg      : in    string
    ;signal   clk      : in    std_logic
    ;signal   sbi_if   : inout t_sbi_if
    );

  -- Check of a std_logic (pin, flag)
  procedure chk_bit
    (constant val      : in    std_logic
    ;constant exp      : in    std_logic
    ;constant msg      : in    string
    );

  -- Wait duration, then check that the line did not move (no frame)
  procedure chk_idle
    (signal   line     : in    std_logic
    ;constant duration : in    time
    ;constant msg      : in    string
    );

  -- Wait n rising edges
  procedure cycles
    (constant n        : in    natural
    ;signal   clk      : in    std_logic
    );

  -- Send one frame on uart_rx_i (bit period : period)
  -- corrupt_parity : send the inverted parity bit
  -- stop_bit       : level of the stop bit ('0' : framing error)
  procedure uart_send
    (constant data           : in    byte_t
    ;constant period         : in    time
    ;signal   rx             : out   std_logic
    ;constant parity         : in    parity_t  := PARITY_NONE
    ;constant corrupt_parity : in    boolean   := false
    ;constant stop_bit       : in    std_logic := '1'
    );

  -- Receive one frame on uart_tx_o and check every bit
  procedure uart_expect
    (constant data     : in    byte_t
    ;constant parity   : in    parity_t
    ;constant msg      : in    string
    ;signal   tx       : in    std_logic
    ;constant period   : in    time      := C_BIT_PERIOD
    );

  -- Byte received with a parity error and RX_PARITY_ERROR = "drop" :
  -- dropped. The parity error event is recorded in isr and the RX FIFO
  -- stays empty : isr[2] (RX FIFO not empty) is cleared, then read right
  -- after the clear (polling) at 0
  procedure chk_rx_dropped
    (constant data     : in    byte_t
    ;signal   clk      : in    std_logic
    ;signal   sbi_if   : inout t_sbi_if
    );

  -- Byte received with a parity error and RX_PARITY_ERROR = "halt" : it
  -- was read from data and RX is halted. It is the last byte of the RX
  -- FIFO : isr[2] (RX FIFO not empty) is cleared, then read right after
  -- the clear (polling) at 0, with the parity error event set. Writing 1
  -- to isr[6] resumes RX
  procedure chk_rx_halted
    (constant data     : in    byte_t
    ;signal   clk      : in    std_logic
    ;signal   sbi_if   : inout t_sbi_if
    );

  -- RX : send data on uart_rx_i, check the parity error flag and read data
  -- (corrupted parity with RX_PARITY_ERROR = "drop" : the byte is
  -- dropped, nothing to read ; with "halt" : the byte is read, then RX
  -- is resumed)
  procedure test_rx
    (constant data           : in    byte_t
    ;constant parity         : in    parity_t
    ;constant corrupt_parity : in    boolean
    ;constant policy         : in    string     -- RX_PARITY_ERROR
    ;signal   clk            : in    std_logic
    ;signal   sbi_if         : inout t_sbi_if
    ;signal   rx             : out   std_logic
    ;signal   par_err        : in    std_logic  -- debug_o.uart_rx.parity_error
    );

  -- TX : write data, check the frame on uart_tx_o
  procedure test_tx
    (constant data     : in    byte_t
    ;constant parity   : in    parity_t
    ;signal   clk      : in    std_logic
    ;signal   sbi_if   : inout t_sbi_if
    ;signal   tx       : in    std_logic
    );

  -- Internal loopback : write data, check the frame on uart_tx_o and read
  -- it back (parity error with RX_PARITY_ERROR = "drop" : the byte is
  -- dropped, nothing to read ; with "halt" : the byte is read, then RX is
  -- resumed)
  procedure test_loopback
    (constant data     : in    byte_t
    ;constant parity   : in    parity_t
    ;constant exp_error: in    std_logic
    ;constant policy   : in    string     -- RX_PARITY_ERROR
    ;signal   clk      : in    std_logic
    ;signal   sbi_if   : inout t_sbi_if
    ;signal   tx       : in    std_logic
    ;signal   par_err  : in    std_logic  -- debug_o.uart_rx.parity_error
    );

  -- Reset pulse, released on a falling edge
  procedure do_reset
    (signal   clk      : in    std_logic
    ;signal   arst_b   : out   std_logic
    );

end package tb_UART_bfm_pkg;

package body tb_UART_bfm_pkg is

  function parity_bit
    (constant data     : in    byte_t
    ;constant parity   : in    parity_t
    ) return std_logic is
    variable v : std_logic := '0';
  begin
    for i in data'range loop
      v := v xor data(i);
    end loop;
    if parity = PARITY_ODD
    then
      v := not v;
    end if;
    return v;
  end function;

  function to_string
    (constant parity   : in    parity_t
    ) return string is
  begin
    case parity is
      when PARITY_EVEN => return "even";
      when PARITY_ODD  => return "odd";
      when others      => return "none";
    end case;
  end function;

  function byte
    (constant i        : in    natural
    ) return byte_t is
  begin
    return std_logic_vector(to_unsigned(i, 8));
  end function;

  procedure wr
    (constant addr     : in    unsigned
    ;constant data     : in    byte_t
    ;constant msg      : in    string
    ;signal   clk      : in    std_logic
    ;signal   sbi_if   : inout t_sbi_if
    ) is
  begin
    sbi_write(addr_value => addr
             ,data_value => data
             ,msg        => msg
             ,clk        => clk
             ,sbi_if     => sbi_if
             ,scope      => C_TB_SCOPE
             ,config     => C_SBI_CFG
             );
  end procedure;

  procedure rd
    (constant addr     : in    unsigned
    ;variable data     : out   byte_t
    ;constant msg      : in    string
    ;signal   clk      : in    std_logic
    ;signal   sbi_if   : inout t_sbi_if
    ) is
  begin
    sbi_read(addr_value => addr
            ,data_value => data
            ,msg        => msg
            ,clk        => clk
            ,sbi_if     => sbi_if
            ,scope      => C_TB_SCOPE
            ,config     => C_SBI_CFG
            );
  end procedure;

  procedure chk
    (constant addr     : in    unsigned
    ;constant data     : in    byte_t
    ;constant msg      : in    string
    ;signal   clk      : in    std_logic
    ;signal   sbi_if   : inout t_sbi_if
    ) is
  begin
    sbi_check(addr_value  => addr
             ,data_exp    => data
             ,msg         => msg
             ,clk         => clk
             ,sbi_if      => sbi_if
             ,alert_level => error
             ,scope       => C_TB_SCOPE
             ,config      => C_SBI_CFG
             );
  end procedure;

  procedure chk_blocking
    (constant data     : in    byte_t
    ;constant msg      : in    string
    ;signal   clk      : in    std_logic
    ;signal   sbi_if   : inout t_sbi_if
    ) is
    variable v_cfg     : t_sbi_bfm_config := C_SBI_CFG;
  begin
    v_cfg.max_wait_cycles := 16 * (C_CLOCK_FREQ / C_BAUD_RATE);
    sbi_check(addr_value  => UART_DATA
             ,data_exp    => data
             ,msg         => msg
             ,clk         => clk
             ,sbi_if      => sbi_if
             ,alert_level => error
             ,scope       => C_TB_SCOPE
             ,config      => v_cfg
             );
  end procedure;

  procedure chk_bit
    (constant val      : in    std_logic
    ;constant exp      : in    std_logic
    ;constant msg      : in    string
    ) is
  begin
    check_value(val, exp, error, msg, C_TB_SCOPE);
  end procedure;

  procedure chk_idle
    (signal   line     : in    std_logic
    ;constant duration : in    time
    ;constant msg      : in    string
    ) is
  begin
    wait for duration;
    check_stable(line, duration, error, msg, C_TB_SCOPE);
  end procedure;

  procedure cycles
    (constant n        : in    natural
    ;signal   clk      : in    std_logic
    ) is
  begin
    for i in 1 to n loop
      wait until rising_edge(clk);
    end loop;
  end procedure;

  procedure uart_send
    (constant data           : in    byte_t
    ;constant period         : in    time
    ;signal   rx             : out   std_logic
    ;constant parity         : in    parity_t  := PARITY_NONE
    ;constant corrupt_parity : in    boolean   := false
    ;constant stop_bit       : in    std_logic := '1'
    ) is
  begin
    log(ID_SEQUENCER, "UART send 0x" & to_hstring(data) & " (parity " & to_string(parity) & ")", C_TB_SCOPE);
    rx <= '0'; -- Start bit
    wait for period;
    for i in 0 to 7 loop
      rx <= data(i);
      wait for period;
    end loop;
    if parity /= PARITY_NONE
    then
      if corrupt_parity
      then
        rx <= not parity_bit(data, parity);
      else
        rx <=     parity_bit(data, parity);
      end if;
      wait for period;
    end if;
    rx <= stop_bit; -- Stop bit
    wait for period;
  end procedure;

  procedure uart_expect
    (constant data     : in    byte_t
    ;constant parity   : in    parity_t
    ;constant msg      : in    string
    ;signal   tx       : in    std_logic
    ;constant period   : in    time      := C_BIT_PERIOD
    ) is
    variable v_data    : byte_t;
  begin
    -- Wait start bit falling edge (it can be already started)
    if tx /= '0'
    then
      wait until tx = '0' for 4 * 12 * period;
      check_value(tx, '0', error, msg & " : start bit detected", C_TB_SCOPE);
      wait for period/2;
    else
      wait for period/2 - tx'last_event;
    end if;
    check_value(tx, '0', error, msg & " : start bit", C_TB_SCOPE);
    for i in 0 to 7 loop
      wait for period;
      v_data(i) := tx;
    end loop;
    check_value(v_data, data, error, msg & " : data bits", C_TB_SCOPE);
    if parity /= PARITY_NONE
    then
      wait for period;
      check_value(tx, parity_bit(data, parity), error, msg & " : parity bit (" & to_string(parity) & ")", C_TB_SCOPE);
    end if;
    wait for period;
    check_value(tx, '1', error, msg & " : stop bit", C_TB_SCOPE);
    -- Stay in the stop bit
    wait for period/4;
  end procedure;

  procedure chk_rx_dropped
    (constant data     : in    byte_t
    ;signal   clk      : in    std_logic
    ;signal   sbi_if   : inout t_sbi_if
    ) is
    variable v_isr     : byte_t;
  begin
    rd(UART_ISR, v_isr, "Read isr after 0x" & to_hstring(data) & " with a parity error", clk, sbi_if);
    chk_bit(v_isr(6), '1', "RX parity error event for 0x" & to_hstring(data));
    wr(UART_ISR, x"44", "Clear RX parity error and RX not empty", clk, sbi_if);
    rd(UART_ISR, v_isr, "Read isr right after the clear", clk, sbi_if);
    chk_bit(v_isr(2), '0', "0x" & to_hstring(data) & " with a parity error dropped (RX FIFO empty)");
  end procedure;

  procedure chk_rx_halted
    (constant data     : in    byte_t
    ;signal   clk      : in    std_logic
    ;signal   sbi_if   : inout t_sbi_if
    ) is
    variable v_isr     : byte_t;
  begin
    wr(UART_ISR, x"04", "Clear RX not empty (polling)", clk, sbi_if);
    rd(UART_ISR, v_isr, "Read isr right after the clear", clk, sbi_if);
    chk_bit(v_isr(6), '1', "RX parity error event (RX halted) for 0x" & to_hstring(data));
    chk_bit(v_isr(2), '0', "0x" & to_hstring(data) & " with a parity error is the last byte of the RX FIFO (RX FIFO empty)");
    wr(UART_ISR, x"40", "Clear RX parity error : RX resumes", clk, sbi_if);
  end procedure;

  procedure test_rx
    (constant data           : in    byte_t
    ;constant parity         : in    parity_t
    ;constant corrupt_parity : in    boolean
    ;constant policy         : in    string
    ;signal   clk            : in    std_logic
    ;signal   sbi_if         : inout t_sbi_if
    ;signal   rx             : out   std_logic
    ;signal   par_err        : in    std_logic
    ) is
    variable v_err           : std_logic;
  begin
    uart_send(data, C_BIT_PERIOD, rx, parity, corrupt_parity);
    wait until rising_edge(clk);
    if corrupt_parity
    then
      v_err := '1';
    else
      v_err := '0';
    end if;
    chk_bit(par_err, v_err, "RX parity error flag for 0x" & to_hstring(data));
    if corrupt_parity and policy = "drop"
    then
      chk_rx_dropped(data, clk, sbi_if);
    else
      chk(UART_DATA, data, "UART RX 0x" & to_hstring(data) & " (parity " & to_string(parity) & ")", clk, sbi_if);
      if corrupt_parity and policy = "halt"
      then
        chk_rx_halted(data, clk, sbi_if);
      end if;
    end if;
  end procedure;

  procedure test_tx
    (constant data     : in    byte_t
    ;constant parity   : in    parity_t
    ;signal   clk      : in    std_logic
    ;signal   sbi_if   : inout t_sbi_if
    ;signal   tx       : in    std_logic
    ) is
  begin
    wr(UART_DATA, data, "Write UART TX 0x" & to_hstring(data), clk, sbi_if);
    uart_expect(data, parity, "UART TX 0x" & to_hstring(data) & " (parity " & to_string(parity) & ")", tx);
  end procedure;

  procedure test_loopback
    (constant data     : in    byte_t
    ;constant parity   : in    parity_t
    ;constant exp_error: in    std_logic
    ;constant policy   : in    string
    ;signal   clk      : in    std_logic
    ;signal   sbi_if   : inout t_sbi_if
    ;signal   tx       : in    std_logic
    ;signal   par_err  : in    std_logic
    ) is
  begin
    test_tx(data, parity, clk, sbi_if, tx);
    wait for C_BIT_PERIOD;
    chk_bit(par_err, exp_error, "Loopback RX parity error flag for 0x" & to_hstring(data));
    if (exp_error = '1') and policy = "drop"
    then
      chk_rx_dropped(data, clk, sbi_if);
    else
      chk(UART_DATA, data, "Loopback RX 0x" & to_hstring(data), clk, sbi_if);
      if (exp_error = '1') and policy = "halt"
      then
        chk_rx_halted(data, clk, sbi_if);
      end if;
    end if;
  end procedure;

  procedure do_reset
    (signal   clk      : in    std_logic
    ;signal   arst_b   : out   std_logic
    ) is
  begin
    arst_b <= '0';
    wait for 100 ns;
    wait until falling_edge(clk);
    arst_b <= '1';
    wait until rising_edge(clk);
  end procedure;

end package body tb_UART_bfm_pkg;
